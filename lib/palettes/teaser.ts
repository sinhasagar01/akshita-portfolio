/* ============================================================================================
   THE HOMEPAGE TEASER'S FIVE — A CURATED SET, NOT A DERIVATION.

   ⚠ FIXED RATHER THAN DERIVED FROM THE PUBLISHED THEME, AND THE REJECTED ALTERNATIVE IS WHY.
   A derived set — published plus its counterpart plus one of each class — would always contain
   whatever is published, so a visitor's first press would always depart from the state they were
   already looking at. That reads like a fix and HIDES THE PROBLEM instead of solving it: the four
   would change under the owner without anyone deciding, and a visitor would never learn the site
   has nine. These five are a design decision, taken once, by a person.

   ---- ⚠ FIVE CLAIMS RATHER THAN FIVE COLOURS -------------------------------------------------

   ⚠ RE-DERIVED 2026-08-19, AND THE AXIS HAD MOVED. The set was described as WARM LIGHT, COOL
   LIGHT, WARM DARK, COLOURED DARK, ACHROMATIC DARK, and two of those five are now false. Measured
   through the resolver the gates use, ground and accent together:

     member          ground   L       C       H       accent  L      C       H
     drawing-office  light   98.50   0.000     0.0            0.0   0.000     0.0
     redline         light   98.45   0.003   106.4           48.8   0.183    29.1
     ink-flare       dark    16.73   0.014    44.3           52.0   0.133    52.0
     nocturne        dark    16.86   0.023   279.6           52.0   0.160   296.0
     photostat       dark    15.43   0.000     0.0           52.0   0.000     0.0

   BOTH LIGHTS HAVE NEUTRAL GROUNDS — 0.000 and 0.003, within 0.003 of each other. "Warm light" and
   "cool light" were claims about a GROUND HUE that no longer exists on either of them, and a hue
   digit at chroma 0.003 is a number rather than a colour. **The two lights differ by their ACCENT
   and by nothing else a visitor can see in the page ground.** So the set no longer varies ground
   hue across five members; it varies ground CLASS across two, and identity within each class.

   ⚠ AND THAT IS THE MEDIA DIRECTION SHOWING UP IN A DERIVED FIGURE RATHER THAN IN A DESCRIPTION.
   A sheet set puts the identity in the mark rather than in the paper. The old axis was the right
   description of a set of hue rotations, and it stopped being true when the hue rotations retired.

   ---- ⚠ FIVE CLAIMS RATHER THAN FIVE COLOURS, RE-DERIVED ------------------------------------

   The set is ACHROMATIC LIGHT, SIGNAL-ONLY LIGHT, WARM DARK, COLOURED DARK, ACHROMATIC DARK.

     drawing-office  the achromatic light, and the published default's origin — ground c 0.000 and
                     accent c 0.000, so there is no hue anywhere in it. The reference the other
                     four are read against.

     redline         THE SAME SHEET WITH ONE SIGNAL, and this is the claim the old "cool light"
                     was standing in for. Its ground is 0.003 from drawing-office's and its accent
                     is c 0.183 at h29.1 — the most chromatic accent in the set. **Two palettes
                     that differ by their signal alone is a thing the system is being asked to
                     survive**, and it is a sharper claim than a second ground hue was.

                     ⚠ ITS COUNTERPART IS `machine-room` AND IS NOT IN THE SET, which is why A7
                     reads four of five rather than five of five. **The pair is MUTUAL** — they
                     point at each other — so redline is pointed back at and its partner simply is
                     not here. That distinction cost a red row: see A10.

     ink-flare       the warm dark — ground c 0.014 at h44.3, accent h52.0.

                     ⚠ THE REGISTRY-PAIR ARGUMENT THAT PUT IT HERE NO LONGER DESCRIBES IT, AND THE
                     PARAGRAPH BELOW IS KEPT WITH THAT SAID. It reads that cream and ink-flare are
                     counterparts so one press shows the same identity on a different ground.
                     Measured now: ink-flare points AT `drawing-office`, and drawing-office points
                     at `photostat`. **The relation is one-way**, and the reciprocated pair inside
                     this set is drawing-office and photostat rather than this one.

     nocturne        the coloured dark — ground c 0.023, THE MOST CHROMATIC GROUND IN THIS SET.
                     ⚠ NOT ON THE SITE, WHICH THIS LINE USED TO SAY: `blueprint` carries 0.063 and
                     is not a member. A superlative scoped to a set has to name the set.

     photostat       the achromatic dark, ground c 0.000. It is the claim nocturne makes in
                     reverse: the ladder alone carries the structure, with nothing for hue to do.

   ---- THE ORIGINAL REASONING, KEPT BECAUSE ITS ARGUMENT SURVIVES ITS SUBJECTS -----------------

   ⚠ THE ACHROMATIC CLAIM WAS ONCE MADE AND WAS FALSE, WHICH IS WHY IT IS ASSERTED NOW. The set was
   first described as "warm light, cool light, coloured dark, ACHROMATIC dark" while containing no
   achromatic member — ink-flare's ground carries chroma 0.014. The prose asserted a structure the
   data did not have, and `A5` pins it to the members rather than to the adjective.

   ⚠ THE PAIR ARGUMENT, WHICH WAS THE REASON A THIRD DARK WAS AN ADDITION RATHER THAN A SWAP.
   Cream and ink-flare were registry counterparts, so ONE PRESS SHOWED THE SAME IDENTITY ON A
   DIFFERENT GROUND — the same warm hue, the same structure, a near-black page. Replacing that dot
   with the achromatic dark would have bought achromatic coverage and lost the demonstration.
   ADDING A FIFTH COST NEITHER. The reasoning is kept rather than deleted, because a reversed
   decision whose reasoning is deleted leaves two contradictory rationales and no record of which
   won — and because the ADDITION-not-SWAP conclusion is still the one in force.

   ⚠ AND IT IS TWO LIGHT AND THREE DARK, NOT A SYMMETRY — worth saying because the set was two and
   two for an arc and reads as though it wants to be even. The claims are not paired: there are two
   ways a light ground varies here and three ways a dark one does. Making it symmetrical again would
   mean dropping a claim to satisfy a shape.

   ⚠ AND IT IS NOT A SET OF COUNTERPART PAIRS, THOUGH FOUR OF THE FIVE POINT AT A MEMBER. Measured:

     drawing-office <-> photostat   MUTUAL, and both are here — the only such pair in the set
     redline        <-> machine-room  MUTUAL, and the partner is NOT here
     ink-flare       -> drawing-office  one-way; drawing-office answers to photostat
     nocturne        -> redline         one-way; redline answers to machine-room

   ⚠ THE FIRST DRAFT OF THIS PARAGRAPH SAID redline "points out and is not pointed back", AND `A10`
   WENT RED ON IT WITHIN THE MINUTE. Being reciprocated and having your partner present are two
   different properties, and a count of "four pair inside the set" cannot tell them apart — which is
   why there are now two rows rather than one. **The prose was the thing that was wrong, on the pass
   whose whole subject was prose being wrong.**

   Reading the set as pairs would make the next person "fix" redline to machine-room and lose the
   signal-only claim.

   ---- ⚠ THE NAMES LIVE HERE AS STRINGS AND CANNOT BE IMPORTED FROM THE REGISTRY ---------------

   `ralph` loads this raw under `--experimental-strip-types`, so it cannot import `lib/theme.ts` in
   any spelling `tsc` also accepts — the same constraint `THEME_METRICS` and `SETTINGS_THEME_VALUES`
   sit under. So these are plain strings and `ralph/tests/palette-teaser.mjs` enforces that every one
   is a real, selectable palette and that the light and dark counts are two and THREE. Single source of
   truth by enforcement rather than by import, which is this repo's standing posture for exactly this.
============================================================================================ */

/** The five the homepage offers. Order is light, light, then the three darks by CLAIM — warm,
 *  coloured, achromatic — read left to right.
 *
 *  ⚠ NOT BY CHROMA, AND THIS COMMENT SAID SO FOR ONE DRAFT. "The three darks by ground chroma
 *  descending to zero" is false: the run is 0.014, 0.023, 0.000. The middle is the MOST chromatic
 *  ground on the site, so the sequence is not monotonic in either direction. Caught because the row
 *  written to assert it had to be given `false` as its expectation to pass — a row agreeing with
 *  broken prose rather than catching it. */
/* ⚠ THE COUNT SPELLED LOCALLY, AND IT IS A FORCED COPY RATHER THAN A PREFERENCE. `lib/theme.ts`
   exports `countWord` and importing it here is the obvious move — it was written, `tsc` accepted
   it, and `ralph` died on it: `Cannot find module .../lib/theme`. Node cannot resolve an
   extensionless `.ts` and `tsc` rejects the extension, which is the constraint this file's own
   header states four paragraphs up and which I read after breaking it.

   Third forced copy in this codebase, after `INSPECTOR_BOUNDS` and `COLLECTION_FILE_RE`. The
   posture is the one this file already names — single source of truth BY ENFORCEMENT rather than
   by import — so `palette-teaser` asserts this word against `countWord()` in the registry, and a
   drift between the two is a red row rather than a silent disagreement. */
const TEASER_COUNT_WORDS = ["zero", "one", "two", "three", "four", "five", "six",
  "seven", "eight", "nine", "ten", "eleven", "twelve"] as const;

/* ⚠ `harbour` WAS THE SECOND LIGHT AND IT IS RETIRED. The set kept its shape — two light, three
   dark — by taking `drawing-office` in its place, which is the published medium rather than a
   nearest-hue substitute. The reasoning above is about a hue relationship harbour had and this
   palette does not, since drawing-office carries no accent hue at all. Kept rather than rewritten,
   because the argument for CURATING five instead of deriving them is unchanged and is the half
   worth keeping. */
export const TEASER_THEMES = ["drawing-office", "redline", "ink-flare", "nocturne", "photostat"] as const;

export type TeaserTheme = (typeof TEASER_THEMES)[number];

/** How many swatches the row offers, spelled for the arrival note. */
export const TEASER_COUNT_WORD: string =
  TEASER_COUNT_WORDS[TEASER_THEMES.length] ?? String(TEASER_THEMES.length);

/**
 * Is the published theme one the teaser offers?
 *
 * ⚠ A LIVE STATE TODAY, NOT AN EDGE CASE. Re-derived 2026-08-19: EIGHT palettes are selectable and
 * five are here, so THREE publishable themes are not — `sapphire`, `machine-room` and `blueprint`.
 * A visitor arriving on one of the three sees a site the five dots cannot explain.
 *
 * ⚠ THIS READ "nine ship, four are not, and sapphire has been the published theme this month", and
 * every figure in it had expired. The count moved when `basalt` retired, and the published theme is
 * `photostat` — which IS in the set, so the live example the sentence rested on is gone too. The
 * numbers carry their date for exactly that reason.
 */
export function publishedIsOffered(publishedTheme: string): boolean {
  return (TEASER_THEMES as readonly string[]).includes(publishedTheme);
}

/**
 * What the teaser says about the state the visitor ARRIVED in, before pressing anything.
 *
 * ⚠ THE ARRIVAL CASE IS A FEATURE OF THE FIXED SET RATHER THAN A COST OF IT. A visitor landing on
 * a palette this row does not contain should be TOLD that — that the site is on a published theme
 * outside the row, and that the full set is larger. That is the page's whole argument arriving
 * before they press anything, and an indicator that only appears after a press leaves this case
 * silently wrong.
 *
 * ⚠ AND THE COUNT IS DERIVED, BECAUSE THIS SENTENCE WAS ALREADY WRONG ONCE IN THE PARAGRAPH ABOVE
 * IT. That prose said "there are nine" and there were ten — stale from the moment `drawing-office`
 * shipped. The user-facing string said "these five" and happened to stay correct only because
 * `TEASER_THEMES` has not changed since it was typed. Same defect, one comment apart, and the
 * visible half was right by luck rather than by construction.
 *
 * The number now comes from `TEASER_THEMES.length`, so adding or removing a swatch moves the
 * sentence with it. The full-set figure is deliberately NOT restated here — the link beside this
 * note already says `All eight` from `selectableCountWord()`, and two derived counts in one breath
 * is a second place to drift.
 *
 * ⚠ AND THAT SENTENCE SAID `All ten` UNTIL THIS PASS — a hardcoded transcription of a DERIVED
 * string, which is the one form of staleness the derivation was meant to make impossible. The link
 * is right because it calls the function; the comment describing the link was wrong because it
 * quoted the answer. Quote the SOURCE, never the value.
 *
 * Returns null when the published theme IS offered, because then the dots explain themselves.
 */
export function arrivalNote(publishedTheme: string): string | null {
  if (publishedIsOffered(publishedTheme)) return null;
  return `Published: ${publishedTheme} — not one of these ${TEASER_COUNT_WORD}`;
}
